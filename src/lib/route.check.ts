import assert from 'node:assert/strict';
import { LOGIN_FAILURE, NETWORK_FAILURE, loginNotice, mailNotice, signupNotice } from './authCopy';
import { isMonthKey, isPlannerPage, modeForPage, pagePath, parseRoute, safeNext, weekMonday, withSearch } from './route';

assert.deepEqual(parseRoute('/'), { name: 'landing' });
assert.deepEqual(parseRoute('/login'), { name: 'login' });
assert.deepEqual(parseRoute('/signup/'), { name: 'signup' });
assert.deepEqual(parseRoute('/forgot-password'), { name: 'forgot' });
assert.deepEqual(parseRoute('/app'), { name: 'calendar', week: null });
assert.deepEqual(parseRoute('/calendar'), { name: 'calendar', week: null });
assert.deepEqual(parseRoute('/app/week/2026-11-24'), { name: 'calendar', week: '2026-11-23' });
assert.deepEqual(parseRoute('/week/2026-01-01'), { name: 'calendar', week: '2025-12-29' });
assert.deepEqual(parseRoute('/app/week/2026-02-31'), { name: 'landing' });
assert.equal(weekMonday('2026-11-24'), '2026-11-23');
assert.equal(pagePath({ name: 'calendar', week: '2026-11-23' }), '/app/week/2026-11-23');
assert.equal(safeNext('/app/week/2026-11-24'), '/app/week/2026-11-23');
assert.deepEqual(parseRoute('/app/habits'), { name: 'habits' });
assert.deepEqual(parseRoute('/habits/'), { name: 'habits' });
assert.deepEqual(parseRoute('/focus'), { name: 'focus' });
assert.deepEqual(parseRoute('/app/focus'), { name: 'focus' });
assert.deepEqual(parseRoute('/settings'), { name: 'settings' });
assert.deepEqual(parseRoute('/app/day/2026-11-20'), { name: 'day', date: '2026-11-20' });
assert.deepEqual(parseRoute('/day/2026-11-20'), { name: 'day', date: '2026-11-20' });
assert.deepEqual(parseRoute('/day/2026-02-31'), { name: 'landing' });
assert.deepEqual(parseRoute('/nope'), { name: 'landing' });
assert.equal(pagePath({ name: 'day', date: '2026-11-20' }), '/app/day/2026-11-20');
assert.equal(pagePath({ name: 'calendar', week: null }), '/app');
assert.equal(pagePath({ name: 'landing' }), '/');
assert.equal(pagePath(parseRoute('/habits')), '/app/habits');
assert.equal(pagePath(parseRoute('/day/2026-11-21')), '/app/day/2026-11-21');
assert.equal(modeForPage({ name: 'day', date: '2026-11-20' }), 'planner');
assert.equal(modeForPage({ name: 'settings' }), null);
assert.equal(modeForPage({ name: 'landing' }), null);
assert.equal(modeForPage({ name: 'login' }), null);
assert.equal(isPlannerPage({ name: 'calendar', week: null }), true);
assert.equal(isPlannerPage({ name: 'login' }), false);
assert.equal(isMonthKey('2026-11'), true);
assert.equal(isMonthKey('2026-13'), false);

assert.equal(safeNext('/app/day/2026-11-20'), '/app/day/2026-11-20');
assert.equal(safeNext('/day/2026-11-20'), '/app/day/2026-11-20');
assert.equal(safeNext('/habits'), '/app/habits');
assert.equal(safeNext('/app/focus'), '/app/focus');
assert.equal(safeNext('/settings'), '/app/settings');
assert.equal(safeNext('/'), null);
assert.equal(safeNext('/login'), null);
assert.equal(safeNext('/signup'), null);
assert.equal(safeNext('/forgot-password'), null);
assert.equal(safeNext('//evil.example/app'), null);
assert.equal(safeNext('https://evil.example/app'), null);
assert.equal(safeNext('http://today-cat.local/app'), null);
assert.equal(safeNext('/\\evil'), null);
assert.equal(safeNext('app'), null);
assert.equal(withSearch('/login?next=/day/2026-11-20'), '/login?next=%2Fapp%2Fday%2F2026-11-20');
assert.equal(withSearch('/login?next=https://evil.example'), '/login');
assert.equal(withSearch('/login?next=/login'), '/login');

assert.equal(loginNotice(null), null);
assert.equal(loginNotice('Неверная почта или пароль.'), LOGIN_FAILURE);
assert.equal(loginNotice('Для этой почты пароль ещё не задан. Нажми „Забыла пароль“.'), LOGIN_FAILURE);
assert.equal(loginNotice('Для этой почты кабинет уже есть. Войди.'), LOGIN_FAILURE);
assert.equal(loginNotice('Слишком много попыток. Подожди немного и попробуй снова.'), 'Слишком много попыток. Подожди немного и попробуй снова.');
assert.equal(loginNotice('Не получилось. Попробуй ещё раз.'), NETWORK_FAILURE);
assert.equal(signupNotice('Для этой почты кабинет уже есть. Войди.'), 'Для этой почты кабинет уже есть. Войди.');
assert.equal(signupNotice('Не получилось. Попробуй ещё раз.'), NETWORK_FAILURE);
assert.equal(mailNotice(null), null);
assert.equal(mailNotice('Письма ещё не подключены.'), 'Письма ещё не подключены.');
assert.equal(mailNotice('Не получилось. Попробуй ещё раз.'), NETWORK_FAILURE);

